import * as esbuild from "esbuild";
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const apiDir = join(root, "api");
const bundleFile = join(apiDir, "index.bundle.cjs");
const entryFile = join(apiDir, "index.js");

mkdirSync(apiDir, { recursive: true });
for (const name of ["index.js", "index.js.map", "index.ts", "index.cjs", "index.mjs", "index.bundle.cjs"]) {
  rmSync(join(apiDir, name), { force: true });
}

await esbuild.build({
  absWorkingDir: root,
  entryPoints: [join(root, "server", "vercelHandler.ts")],
  outfile: bundleFile,
  bundle: true,
  platform: "node",
  target: "node20",
  format: "cjs",
  logLevel: "info",
  alias: {
    "@shared": join(root, "shared"),
  },
  external: ["@aws-sdk/*"],
});

writeFileSync(
  entryFile,
  [
    "/* generated by scripts/build-vercel-api.mjs — do not edit */",
    "const app = require(\"./index.bundle.cjs\");",
    "module.exports = app.default || app;",
    "",
  ].join("\n"),
  "utf8",
);

writeFileSync(
  join(apiDir, "package.json"),
  `${JSON.stringify({ type: "commonjs" }, null, 2)}\n`,
  "utf8",
);
writeFileSync(join(apiDir, ".bundle-stamp"), new Date().toISOString(), "utf8");

console.log(`[build-vercel-api] wrote ${entryFile}`);
